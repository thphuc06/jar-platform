package io.github.thphuc06.jars.infra;

import java.util.List;
import java.util.Map;
import software.amazon.awscdk.Acknowledgment;
import software.amazon.awscdk.CfnOutput;
import software.amazon.awscdk.Duration;
import software.amazon.awscdk.RemovalPolicy;
import software.amazon.awscdk.Stack;
import software.amazon.awscdk.StackProps;
import software.amazon.awscdk.Validations;
import software.amazon.awscdk.services.cloudwatch.Alarm;
import software.amazon.awscdk.services.cloudwatch.ComparisonOperator;
import software.amazon.awscdk.services.cloudwatch.Metric;
import software.amazon.awscdk.services.cloudwatch.TreatMissingData;
import software.amazon.awscdk.services.cloudwatch.actions.SnsAction;
import software.amazon.awscdk.services.ec2.SubnetSelection;
import software.amazon.awscdk.services.rds.AuroraPostgresClusterEngineProps;
import software.amazon.awscdk.services.rds.AuroraPostgresEngineVersion;
import software.amazon.awscdk.services.rds.BackupProps;
import software.amazon.awscdk.services.rds.ClusterInstance;
import software.amazon.awscdk.services.rds.Credentials;
import software.amazon.awscdk.services.rds.CredentialsBaseOptions;
import software.amazon.awscdk.services.rds.DatabaseCluster;
import software.amazon.awscdk.services.rds.DatabaseClusterEngine;
import software.amazon.awscdk.services.rds.ServerlessV2ClusterInstanceProps;
import software.amazon.awscdk.services.sns.ITopic;
import software.constructs.Construct;

/**
 * Aurora PostgreSQL Serverless v2 that scales to ZERO (ADR-0008): when no connection is open for the auto-pause
 * duration it stops billing compute and only storage remains. Kept between test sessions (cost-and-budget §3).
 */
public class DataStack extends Stack {

    /** Pause after 5 minutes without connections (the minimum AWS allows). */
    static final Duration AUTO_PAUSE = Duration.minutes(5);

    private final DatabaseCluster cluster;

    public DataStack(
            Construct scope, String id, StackProps props, EnvConfig config, NetworkStack network, ITopic alarms) {
        super(scope, id, props);

        cluster = DatabaseCluster.Builder.create(this, "Database")
                .clusterIdentifier(config.name("db"))
                .engine(DatabaseClusterEngine.auroraPostgres(AuroraPostgresClusterEngineProps.builder()
                        .version(AuroraPostgresEngineVersion.VER_17_9) // same major as local/compose.yaml and tests
                        .build()))
                .writer(ClusterInstance.serverlessV2(
                        "writer",
                        ServerlessV2ClusterInstanceProps.builder()
                                .publiclyAccessible(false)
                                .build()))
                .serverlessV2MinCapacity(0)
                .serverlessV2MaxCapacity(2) // a cap on the bill: 2 ACU = $0.40/hour at most
                .serverlessV2AutoPauseDuration(AUTO_PAUSE)
                .vpc(network.vpc())
                .vpcSubnets(SubnetSelection.builder().subnetGroupName("data").build())
                .securityGroups(List.of(network.dbSecurityGroup()))
                .defaultDatabaseName("jars")
                // password generated by Secrets Manager; ECS reads it from there (P3.4), it never appears in config
                .credentials(Credentials.fromGeneratedSecret(
                        "jars_admin",
                        CredentialsBaseOptions.builder()
                                .secretName(config.name("db-credentials"))
                                .build()))
                .storageEncrypted(true)
                .iamAuthentication(true)
                // the RDS Data API lets SQL reach the cluster over the AWS API (IAM + the secret), with no network
                // path into the isolated subnets: used to check the cluster, and wakes it up like any connection
                .enableDataApi(true)
                .backup(BackupProps.builder().retention(Duration.days(1)).build())
                // data outlives "cdk destroy": deleting the stack needs deletion protection turned off first, and
                // even then leaves a final snapshot
                .deletionProtection(true)
                .removalPolicy(RemovalPolicy.SNAPSHOT)
                .build();

        // A cluster that never pauses costs 0.5 ACU x 730 h x $0.20 = ~$73/month. Minimum over each hour > 0 means it
        // never reached 0 ACU in that hour; six such hours in a row = something keeps it awake (pool, job, GUI tool).
        Alarm.Builder.create(this, "NeverPauses")
                .alarmName(config.name("db-never-pauses"))
                .alarmDescription("Aurora has not paused for 6 hours: an open connection keeps it awake (~$73/month)")
                .metric(Metric.Builder.create()
                        .namespace("AWS/RDS")
                        .metricName("ServerlessDatabaseCapacity")
                        .dimensionsMap(Map.of("DBClusterIdentifier", cluster.getClusterIdentifier()))
                        .statistic("Minimum")
                        .period(Duration.hours(1))
                        .build())
                .comparisonOperator(ComparisonOperator.GREATER_THAN_THRESHOLD)
                .threshold(0)
                .evaluationPeriods(6)
                .treatMissingData(TreatMissingData.NOT_BREACHING)
                .build()
                .addAlarmAction(new SnsAction(alarms));

        Validations.of(cluster)
                .acknowledge(Acknowledgment.builder()
                        .id("AwsSolutions::AwsSolutions-SMG4")
                        .reason("Rotation needs a Lambda that reaches both Secrets Manager and the database: from"
                                + " the isolated data subnets that means an interface endpoint (~$9.5/month per AZ)"
                                + " or NAT, both ruled out by ADR-0013. ECS also reads the secret only at task start,"
                                + " so a rotated password breaks new connections of running tasks. Planned instead:"
                                + " IAM database authentication (enabled) with short-lived tokens, no static password.")
                        .build());

        output("ClusterArn", cluster.getClusterArn(), "for aws rds-data execute-statement --resource-arn");
        output("SecretArn", cluster.getSecret().getSecretArn(), "for aws rds-data execute-statement --secret-arn");
        output(
                "ClusterEndpoint",
                cluster.getClusterEndpoint().getHostname(),
                "JDBC host (reachable only inside the VPC)");
    }

    public DatabaseCluster cluster() {
        return cluster;
    }

    private void output(String id, String value, String description) {
        CfnOutput.Builder.create(this, id).value(value).description(description).build();
    }
}
