package io.github.thphuc06.jars.identity.internal.persistence;

import io.github.thphuc06.jars.identity.internal.domain.User;
import java.time.Instant;
import java.util.Optional;
import java.util.UUID;
import org.springframework.data.jpa.repository.JpaRepository;
import org.springframework.data.jpa.repository.Modifying;
import org.springframework.data.jpa.repository.Query;
import org.springframework.data.repository.query.Param;

public interface UserRepository extends JpaRepository<User, UUID> {

    @Query("select u.id from User u where u.cognitoSub = :sub")
    Optional<UUID> findIdByCognitoSub(@Param("sub") String cognitoSub);

    /**
     * Race-free create: when two first requests arrive together exactly one insert wins and the other returns 0, with
     * no exception that would abort the transaction. The id is generated by the caller because this bypasses Hibernate.
     */
    @Modifying
    @Query(value = """
                    INSERT INTO users (id, cognito_sub, locale, created_at, updated_at)
                    VALUES (:id, :sub, :locale, :now, :now)
                    ON CONFLICT (cognito_sub) DO NOTHING
                    """, nativeQuery = true)
    int insertIfAbsent(
            @Param("id") UUID id,
            @Param("sub") String cognitoSub,
            @Param("locale") String locale,
            @Param("now") Instant now);
}
