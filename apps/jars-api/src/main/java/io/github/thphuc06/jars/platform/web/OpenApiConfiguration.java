package io.github.thphuc06.jars.platform.web;

import io.swagger.v3.core.converter.ModelConverter;
import io.swagger.v3.oas.models.Components;
import io.swagger.v3.oas.models.OpenAPI;
import io.swagger.v3.oas.models.info.Info;
import io.swagger.v3.oas.models.media.Content;
import io.swagger.v3.oas.models.media.MediaType;
import io.swagger.v3.oas.models.media.Schema;
import io.swagger.v3.oas.models.responses.ApiResponse;
import io.swagger.v3.oas.models.security.SecurityScheme;
import io.swagger.v3.oas.models.servers.Server;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Map;
import org.springdoc.core.customizers.OpenApiCustomizer;
import org.springframework.context.annotation.Bean;
import org.springframework.context.annotation.Configuration;

/**
 * The parts of the OpenAPI document that the controllers cannot describe: title, server, security scheme and the
 * RFC 9457 problem returned by every error. The document itself is generated by springdoc (profile "local") and
 * committed as contracts/openapi/jars-api.yaml; see OpenApiContractTest.
 */
@SuppressWarnings({"rawtypes", "unchecked"})
@Configuration(proxyBeanMethods = false)
class OpenApiConfiguration {

    @Bean
    OpenAPI jarsOpenApi() {
        return new OpenAPI()
                .info(new Info()
                        .title("Jars Platform API")
                        .version("v1")
                        .description("Personal finance with the 6-jar method. Money is a decimal string in VND "
                                + "(\"85000.00\"); errors are RFC 9457 problems (application/problem+json)."))
                // relative: the web app calls the API on its own origin (Vite proxy locally), so no host is baked in
                .servers(List.of(new Server().url("/")))
                .components(new Components()
                        .addSecuritySchemes(
                                ApiContractRules.BEARER,
                                new SecurityScheme()
                                        .type(SecurityScheme.Type.HTTP)
                                        .scheme("bearer")
                                        .bearerFormat("JWT")
                                        .description("Cognito ACCESS token (an ID token is rejected). GET needs scope "
                                                + ApiContractRules.READ_SCOPE + ", every other method "
                                                + ApiContractRules.WRITE_SCOPE + "."))
                        .addSchemas("Problem", problem())
                        .addResponses("Unauthorized", problemResponse("Missing, expired or invalid access token"))
                        .addResponses("Forbidden", problemResponse("The access token lacks the required scope"))
                        .addResponses(
                                "Problem",
                                problemResponse("Any other error. `type` names it: e.g. .../validation-failed (422, "
                                        + "with `errors`), .../insufficient-jar-balance (422), "
                                        + ".../idempotency-key-reused (422), .../concurrent-modification (409), "
                                        + ".../transaction-not-found (404)")));
    }

    @Bean
    ModelConverter dtoSchemaConverter() {
        return new DtoSchemaConverter();
    }

    @Bean
    OpenApiCustomizer apiContractRules() {
        return new ApiContractRules();
    }

    private static Schema problem() {
        Schema fieldError = new Schema()
                .types(types("object"))
                .addProperty("field", new Schema().types(types("string")))
                .addProperty("message", new Schema().types(types("string")))
                .required(List.of("field", "message"));
        return new Schema()
                .types(types("object"))
                .description("RFC 9457 problem details, plus traceId (quote it when reporting an error)")
                .properties(Map.of(
                        "type", new Schema().types(types("string")).format("uri"),
                        "title", new Schema().types(types("string")),
                        "status", new Schema().types(types("integer")).format("int32"),
                        "detail", new Schema().types(types("string")),
                        "instance", new Schema().types(types("string")),
                        "traceId", new Schema().types(types("string")),
                        "errors",
                                new Schema()
                                        .types(types("array"))
                                        .items(fieldError)
                                        .description("Only for validation-failed: one entry per invalid field")))
                .required(List.of("status", "title", "type"));
    }

    private static ApiResponse problemResponse(String description) {
        return new ApiResponse()
                .description(description)
                .content(new Content()
                        .addMediaType(
                                "application/problem+json",
                                new MediaType().schema(new Schema().$ref("#/components/schemas/Problem"))));
    }

    private static LinkedHashSet<String> types(String type) {
        return new LinkedHashSet<>(List.of(type));
    }
}
